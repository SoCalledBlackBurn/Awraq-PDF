// Comments, multi-page selection, undo of page operations, page numbers, command palette, properties, saving
const fs = require('fs'); const { execFileSync } = require('child_process'); const { PDFDocument } = require('pdf-lib');
const { launch, kill, ok, samplePdf, focusDoc, pageCount } = require('./helpers');
module.exports = async () => {
  const F = await samplePdf('editing.pdf'); const { app, win, logs } = await launch({ args: [F] });
  await win.waitForSelector('.tab'); await win.waitForTimeout(1500);
  ok(await pageCount(win) === '/ 6', 'opens with 6 pages');
  await win.click('#bTools'); await win.click('button[data-tool=rect]');
  const box = await win.locator('.page[data-page-number="1"] canvas.annotOverlay').boundingBox();
  await win.mouse.move(box.x + 100, box.y + 200); await win.mouse.down(); await win.mouse.move(box.x + 300, box.y + 320, { steps: 5 }); await win.mouse.up(); await win.waitForTimeout(300);
  ok(/\b1 comment\b/.test(await win.textContent('#stRight')), 'rectangle comment added');
  ok(await win.locator('.tab.dirty').count() === 1, 'tab marked as changed');
  await win.keyboard.press('Escape');
  await win.click('#p-thumbs .thumb[data-n="2"]'); await win.click('#p-thumbs .thumb[data-n="3"]', { modifiers: ['Control'] });
  ok(await win.locator('#p-thumbs .thumb.sel').count() === 2, 'Ctrl+click selects two thumbnails');
  ok(/2 pages selected/.test(await win.textContent('#stLeft')), 'status bar shows the selection');
  await win.click('#p-thumbs .thumb[data-n="3"]', { button: 'right' }); await win.click('#ctx button.danger'); await win.waitForTimeout(1500);
  ok(await pageCount(win) === '/ 4', 'deleting the selection leaves 4 pages');
  await focusDoc(win); await win.keyboard.press('Control+z'); await win.waitForTimeout(1500);
  ok(await pageCount(win) === '/ 6', 'Ctrl+Z brings the pages back');
  ok(/\b1 comment\b/.test(await win.textContent('#stRight')), 'the comment survives undo');
  await win.keyboard.press('Control+y'); await win.waitForTimeout(1500); ok(await pageCount(win) === '/ 4', 'Ctrl+Y deletes them again');
  await win.keyboard.press('Control+z'); await win.waitForTimeout(1500); ok(await pageCount(win) === '/ 6', 'and Ctrl+Z restores again');
  await win.keyboard.press('Control+k'); await win.waitForSelector('#palette:not([hidden])'); await win.fill('#palQ', 'page numbers'); await win.waitForTimeout(100);
  ok(/page numbers/i.test(await win.textContent('#palList button.on span')), 'command palette finds "Add page numbers"');
  await win.keyboard.press('Enter'); await win.waitForSelector('#dlg[open]'); await win.selectOption('#dlg select >> nth=1', 'nN'); await win.click('#dlgBtns .primary'); await win.waitForTimeout(2000);
  await win.keyboard.press('Control+k'); await win.fill('#palQ', '5'); await win.keyboard.press('Enter'); await win.waitForTimeout(500);
  ok((await win.inputValue('#pageInput')) === '5', 'typing a number in the palette jumps to that page');
  await win.click('#bMenu'); await win.click('#menu button[data-act=editprops]'); await win.waitForSelector('#dlg[open]');
  await win.fill('#dlg input >> nth=0', 'عنوان جديد — New Title'); await win.click('#dlgBtns .primary'); await win.waitForTimeout(300);
  await focusDoc(win); await win.keyboard.press('Control+s'); await win.waitForTimeout(2500);
  ok(await win.locator('.tab.dirty').count() === 0, 'saving clears the changed mark');
  const doc = await PDFDocument.load(fs.readFileSync(F));
  ok(doc.getPageCount() === 6, 'saved file has 6 pages'); ok(doc.getTitle() === 'عنوان جديد — New Title', 'edited title (Arabic) written to the file');
  ok(doc.getPages().reduce((s, p) => s + (p.node.Annots() ? p.node.Annots().size() : 0), 0) === 1, 'comment saved as a real PDF annotation');
  const txt = execFileSync('pdftotext', [F, '-']).toString();
  ok([1, 4, 5, 6].every(n => new RegExp(n + ' ?/ ?6').test(txt)), 'page numbers on every page, including landscape and rotated ones');
  ok(!fs.readdirSync(require('path').dirname(F)).some(f => f.includes('.awraq-tmp')), 'no temporary files left next to the document');
  ok(!logs.length, 'no errors in the console' + (logs.length ? ': ' + logs.join(' | ') : ''));
  await kill(app);
};
